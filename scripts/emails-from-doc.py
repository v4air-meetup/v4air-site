"""Copy the email texts from the Google Doc "V4AIR form emails" into backend/Emails.gs.

The Doc is the one place the wording lives; the mailer in backend/Code.gs only reads EMAILS from Emails.gs.
Each Doc tab after "How it works" is one email: a "Sent:" rule line, a "Keep the words..." line, "Subject: ...", then the body.

  python3 scripts/emails-from-doc.py           # rewrite backend/Emails.gs from the Doc
  python3 scripts/emails-from-doc.py --check   # exit 1 if backend/Emails.gs differs from the Doc

Needs a Google OAuth token with Docs read access in ~/.claude_google_token.json (or GOOGLE_TOKEN_FILE).
"""
import json, os, sys
from google.oauth2.credentials import Credentials
from googleapiclient.discovery import build

DOC_ID = '1EkQNlVa_DGdI5lYP727lhxpAr0XhKTinMEud09Y_g9g'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'backend', 'Emails.gs')


def text(content):
    return ''.join(r.get('textRun', {}).get('content', '') for el in content if 'paragraph' in el for r in el['paragraph']['elements'])


def tabs(t):
    for x in t:
        yield x
        yield from tabs(x.get('childTabs', []))


def emails():
    tok = json.load(open(os.environ.get('GOOGLE_TOKEN_FILE', os.path.expanduser('~/.claude_google_token.json'))))
    docs = build('docs', 'v1', credentials=Credentials.from_authorized_user_info(tok), cache_discovery=False)
    doc = docs.documents().get(documentId=DOC_ID, includeTabsContent=True).execute()
    out = {}
    for t in tabs(doc['tabs']):
        title = t['tabProperties']['title']
        if title == 'How it works':
            continue
        lines = text(t['documentTab']['body']['content']).replace('\u000b', '\n').split('\n')
        subj = [i for i, ln in enumerate(lines) if ln.startswith('Subject:')]
        if not subj:
            sys.exit(f'tab "{title}" has no "Subject:" line')
        body = '\n'.join(lines[subj[0] + 1:]).strip('\n') + '\n'
        out[title] = {'subject': lines[subj[0]][len('Subject:'):].strip(), 'body': body}
    return out


def render(data):
    return ('/* Generated by scripts/emails-from-doc.py from the Google Doc "V4AIR form emails". Do not edit here: edit the Doc,\n'
            '   then run the script and commit. Keys are the Doc tab names. Placeholders: {NAME} {ID} {LINK} {NOMINATE_LINK}\n'
            '   {UNSUBSCRIBE_LINK} {SENT_DATE} {STARTED_DATE} {NOMINATOR}. */\n'
            'var EMAILS = ' + json.dumps(data, indent=2, ensure_ascii=False) + ';\n')


if __name__ == '__main__':
    new = render(emails())
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        print('backend/Emails.gs matches the Doc' if old == new else 'backend/Emails.gs differs from the Doc: run scripts/emails-from-doc.py')
        sys.exit(old != new)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(new)
    print(f'wrote {OUT}')
